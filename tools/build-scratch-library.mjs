// Generate src/scratchlib.js — the catalog of Scratch's built-in costumes,
// backdrops and sounds, so the LLM can name a real asset and the compiler can
// emit a correct costume/sound entry (assetId + md5ext + metadata) for it.
//
// Source of truth: the official scratch-gui library manifests on GitHub. Each
// entry already carries everything an .sb3 costume/sound object needs. We keep
// only those fields, key by lower-cased name (names are unique case-insensitively
// across each set — verified), and write a compact ES module.
//
// Run:  node tools/build-scratch-library.mjs   (re-run to refresh from upstream)

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'https://raw.githubusercontent.com/scratchfoundation/scratch-gui';
const REF = 'develop';
const BASE = `${REPO}/${REF}/src/lib/libraries`;

async function fetchManifest(name) {
  const res = await fetch(`${BASE}/${name}.json`);
  if (!res.ok) throw new Error(`Failed to fetch ${name}.json: ${res.status}`);
  return res.json();
}

const ext = (md5ext) => md5ext.slice(md5ext.lastIndexOf('.') + 1);

// name -> { name, assetId, md5ext, dataFormat, bitmapResolution, rotationCenterX, rotationCenterY }
function image(list) {
  const out = {};
  for (const c of list) {
    out[c.name.toLowerCase()] = {
      name: c.name,
      assetId: c.assetId,
      md5ext: c.md5ext,
      dataFormat: ext(c.md5ext),
      bitmapResolution: c.bitmapResolution || 1,
      rotationCenterX: c.rotationCenterX || 0,
      rotationCenterY: c.rotationCenterY || 0,
    };
  }
  return out;
}

// name -> { name, assetId, md5ext, dataFormat, rate, sampleCount }
function audio(list) {
  const out = {};
  for (const s of list) {
    out[s.name.toLowerCase()] = {
      name: s.name,
      assetId: s.assetId,
      md5ext: s.md5ext,
      dataFormat: ext(s.md5ext),
      rate: s.rate || 48000,
      sampleCount: s.sampleCount || 0,
    };
  }
  return out;
}

const [costumes, backdrops, sounds] = await Promise.all([
  fetchManifest('costumes'),
  fetchManifest('backdrops'),
  fetchManifest('sounds'),
]);

const COSTUMES = image(costumes);
const BACKDROPS = image(backdrops);
const SOUNDS = audio(sounds);

const header =
  '// AUTO-GENERATED by tools/build-scratch-library.mjs — do not edit by hand.\n' +
  '//\n' +
  '// Scratch\'s built-in costumes, backdrops and sounds, keyed by lower-cased\n' +
  '// name. Each value is ready to drop into an .sb3 costume/sound object; the\n' +
  '// bytes live on the Scratch asset CDN (referenced/fetched by md5ext).\n' +
  `// Source: scratchfoundation/scratch-gui@${REF}\n` +
  `// Counts: ${Object.keys(COSTUMES).length} costumes, ` +
  `${Object.keys(BACKDROPS).length} backdrops, ${Object.keys(SOUNDS).length} sounds.\n\n`;

const dump = (name, obj) =>
  `export const ${name} = ${JSON.stringify(obj, null, 0)};\n`;

const body = [
  dump('COSTUMES', COSTUMES),
  dump('BACKDROPS', BACKDROPS),
  dump('SOUNDS', SOUNDS),
].join('\n');

const out = resolve(ROOT, 'src', 'scratchlib.js');
writeFileSync(out, header + body);
console.log(
  `Wrote ${out}\n  ${Object.keys(COSTUMES).length} costumes, ` +
  `${Object.keys(BACKDROPS).length} backdrops, ${Object.keys(SOUNDS).length} sounds`
);

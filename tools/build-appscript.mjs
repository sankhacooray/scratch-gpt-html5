// Bundle the ES-module frontend into a single Apps Script HTML file.
//
// HtmlService can't resolve ES `import` across project files, so we inline a
// tiny lazy module system and concatenate src/*.js (entry: app.js) into one
// classic <script>, injected into app.html. Output is written into the sibling
// clasp project at ../scratch-gpt-appscript/src/Index.html, served by Code.gs.
//
// Run:  node tools/build-appscript.mjs   (or: npm run build:appscript)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = resolve(ROOT, 'src');
const ENTRY = 'app';

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*['"]\.\/([A-Za-z0-9_$]+)\.js['"];?\s*$/gm;
const EXPORT_FN_RE = /^export\s+(?:async\s+)?function\s+([A-Za-z0-9_$]+)/gm;
const EXPORT_CONST_RE = /^export\s+const\s+([A-Za-z0-9_$]+)/gm;

function load(name, seen, order) {
  if (seen.has(name)) return;
  seen.add(name);
  const src = readFileSync(resolve(SRC, name + '.js'), 'utf8');

  // Recurse into dependencies first (order is irrelevant for the lazy loader,
  // but this keeps the bundle readable / deterministic).
  let m;
  IMPORT_RE.lastIndex = 0;
  while ((m = IMPORT_RE.exec(src))) load(m[2], seen, order);

  const exports = [];
  EXPORT_FN_RE.lastIndex = 0;
  while ((m = EXPORT_FN_RE.exec(src))) exports.push(m[1]);
  EXPORT_CONST_RE.lastIndex = 0;
  while ((m = EXPORT_CONST_RE.exec(src))) exports.push(m[1]);

  const body = src
    .replace(IMPORT_RE, (_all, names, dep) => `const {${names.trim()}} = __require('${dep}');`)
    .replace(/^export\s+(async\s+function)/gm, '$1')
    .replace(/^export\s+function/gm, 'function')
    .replace(/^export\s+const/gm, 'const');

  const assigns = exports.map((n) => `  __exports.${n} = ${n};`).join('\n');
  order.push(
    `__factory[${JSON.stringify(name)}] = function (__exports, __require) {\n` +
    body +
    (assigns ? `\n${assigns}\n` : '\n') +
    `};`
  );
}

function buildBundle() {
  const seen = new Set();
  const order = [];
  load(ENTRY, seen, order);
  return [
    '(function () {',
    'var __cache = {}, __factory = {};',
    'function __require(n) {',
    '  if (__cache[n]) return __cache[n];',
    '  var m = {}; __cache[n] = m; __factory[n](m, __require); return m;',
    '}',
    order.join('\n'),
    `__require(${JSON.stringify(ENTRY)});`,
    '})();',
  ].join('\n');
}

function buildHtml() {
  let html = readFileSync(resolve(ROOT, 'app.html'), 'utf8');
  let bundle = buildBundle();
  // Guard against the bundle accidentally closing the <script> or tripping the
  // Apps Script templating scanner.
  bundle = bundle.replace(/<\/script>/gi, '<\\/script>');

  const inject =
    '  <!-- info injected by Code.gs template; bundle generated by tools/build-appscript.mjs -->\n' +
    '  <script>\n' +
    '    window.SCRATCH_INFO = <?!= info ?>;\n' +
    '    window.SCRATCH_USER = (window.SCRATCH_INFO && window.SCRATCH_INFO.email) || "";\n' +
    '  </script>\n' +
    '  <script>\n' + bundle + '\n  </script>';

  if (!html.includes('<script type="module" src="src/app.js"></script>')) {
    throw new Error('Could not find the module <script> tag to replace in app.html');
  }
  html = html.replace('  <script type="module" src="src/app.js"></script>', inject);
  return html;
}

// Output into the sibling clasp project's rootDir.
const out = resolve(ROOT, '..', 'scratch-gpt-appscript', 'src', 'Index.html');
writeFileSync(out, buildHtml());
console.log('Wrote ' + out);
